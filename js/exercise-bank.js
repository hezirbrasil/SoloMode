export const INITIAL_EXERCISES=BASE.map(([name,muscle,category])=>({id:makeId(),name,muscle,category,type:'Full Body',available:true,custom:false}));
export const muscles=[...new Set(BASE.map(item=>item[1]))];
export function addExercise(bank,data){const name=data.name.trim();if(!name)throw new Error('Informe o nome do exercício.');if(bank.some(item=>item.name.toLocaleLowerCase('pt-BR')===name.toLocaleLowerCase('pt-BR')))throw new Error('Já existe um exercício com esse nome.');return [...bank,{id:makeId(),name,muscle:data.muscle.trim(),category:(data.category||'Geral').trim(),type:data.type==='Leg Blast'?'Leg Blast':'Full Body',available:true,custom:false}]}
export function updateExercise(bank,id,data){const name=data.name.trim();if(bank.some(item=>item.id!==id&&item.name.toLocaleLowerCase('pt-BR')===name.toLocaleLowerCase('pt-BR')))throw new Error('Já existe um exercício com esse nome.');return bank.map(item=>item.id===id?{...item,...data,name,muscle:data.muscle.trim(),category:(data.category||'Geral').trim()}:item)}
export function removeExercise(bank,id){return bank.filter(item=>item.id!==id)}
export function searchExercises(bank,{query='',muscle='',type='',excluded=[]}={}){const q=query.trim().toLocaleLowerCase('pt-BR');return bank.filter(item=>!excluded.includes(item.id)&&(!muscle||item.muscle===muscle)&&(!type||item.type===type)&&(!q||item.name.toLocaleLowerCase('pt-BR').includes(q)||item.muscle.toLocaleLowerCase('pt-BR').includes(q)))}
export function canAddExercise(blocks,exercise){const sameSource=blocks.some(block=>block.sourceId===exercise.id||block.exercises?.some(item=>item.sourceId===exercise.id));if(sameSource)return false;if(exercise.name==='Stiff unilateral E')return !blocks.some(b=>b.name==='Stiff unilateral E'||b.exercises?.some(e=>e.name==='Stiff unilateral E'));if(exercise.name==='Stiff unilateral D')return !blocks.some(b=>b.name==='Stiff unilateral D'||b.exercises?.some(e=>e.name==='Stiff unilateral D'));return true}
export function makeExerciseBlock(exercise,work='00:50',rest='00:10'){return {id:makeId(),name:exercise.name,sourceId:exercise.id||null,muscle:exercise.muscle||'Personalizado',category:exercise.category||'Personalizado',work,rest,groupId:null,exercises:null}}
